#!/usr/bin/env node
// #323-E · moves user-facing Polish texts of components into the catalog (src/i18n/catalog/pl.generated.ts) and replaces
// them with t("key") calls. Re-runnable: already wrapped texts are left alone; new texts get new keys.
//
//   node scripts/i18n-extract.mjs [--dry] <files…>
//
// What is taken (inside functions only — module-level constants are reported, not changed, because they are evaluated
// once and would not follow a language switch):
//   * JSX text children;
//   * string attributes meant for people: aria-label, title, placeholder, alt, label, description, …;
//   * string / template literals rendered directly in JSX ({cond ? "A" : "B"}, {`${n} z ${m}`});
//   * values of object properties named title / description / label / message / text / hint / … (toasts, options);
//   * arguments of setError / setMessage / setNotice-like setters.
// Template literals become t("key", { name: expr }) with "{name}" placeholders, so a translation can reorder them.
// Nothing typed by users passes through here: only literals written in the source code.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const ts = require("typescript");

const args = process.argv.slice(2);
const dry = args.includes("--dry");
const files = args.filter((a) => !a.startsWith("--"));
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..");
const CATALOG = path.join(ROOT, "src/i18n/catalog/pl.generated.ts");

const USER_ATTRS = new Set(["aria-label", "title", "placeholder", "alt", "label", "description", "aria-description", "aria-valuetext", "emptyText", "emptyLabel", "hint", "heading", "subtitle", "caption", "tooltip", "confirmLabel", "cancelLabel", "actionLabel", "note", "summary", "detail", "message", "text", "srLabel"]);
const USER_PROPS = new Set(["title", "description", "label", "hint", "note", "message", "text", "placeholder", "summary", "heading", "caption", "tooltip", "detail", "reason", "emptyText", "helper", "subtitle", "desc", "badge", "cta", "actionLabel", "confirmLabel", "cancelLabel", "explanation", "headline", "lead", "body", "warning", "info", "sr", "srLabel", "short", "long", "question", "answer", "tip"]);
const SETTER = /^set[A-Z]\w*(Error|Message|Notice|Status|Text|Hint|Problem|Warning|Feedback|Info)$/;

const fold = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/ł/g, "l").replace(/Ł/g, "L");
const slugOf = (text) => fold(text).toLowerCase().match(/[a-z0-9]+/g)?.slice(0, 5).join("_").slice(0, 40) || "text";
const prefixOf = (file) => path.basename(file).replace(/\.(tsx?|mjs)$/, "").replace(/[-.]+(\w)/g, (_, c) => c.toUpperCase()).replace(/^\w/, (c) => c.toLowerCase());
const letters = (s) => (s.match(/[A-Za-zÀ-ž]/g) ?? []).length;
const looksHuman = (s) => letters(s) >= 2 && !/^[a-z0-9_.:\/#?=&%-]+$/.test(s) && (/\s/.test(s.trim()) || /[ąćęłńóśźżĄĆĘŁŃÓŚŹŻ]/.test(s) || /^[A-ZĄĆĘŁŃÓŚŹŻ]/.test(s.trim()));
const ENTITIES = { "&nbsp;": " ", "&quot;": '"', "&apos;": "'", "&amp;": "&", "&lt;": "<", "&gt;": ">", "&hellip;": "…", "&mdash;": "—", "&ndash;": "–" };
const decode = (s) => s.replace(/&[a-z]+;/g, (e) => ENTITIES[e] ?? e);

/** JSX's own whitespace rule (as in Babel): what this text node renders. */
function jsxRendered(raw) {
  const lines = raw.split(/\r\n|\n|\r/);
  let last = 0;
  lines.forEach((line, i) => { if (/[^ \t]/.test(line)) last = i; });
  let out = "";
  lines.forEach((line, i) => {
    let trimmed = line.replace(/\t/g, " ");
    if (i !== 0) trimmed = trimmed.replace(/^[ ]+/, "");
    if (i !== lines.length - 1) trimmed = trimmed.replace(/[ ]+$/, "");
    if (trimmed) { if (i !== last) trimmed += " "; out += trimmed; }
  });
  return decode(out);
}

// ── catalog ───────────────────────────────────────────────────────────────────
function readCatalog() {
  if (!existsSync(CATALOG)) return {};
  const source = readFileSync(CATALOG, "utf8");
  const json = source.slice(source.indexOf("{"), source.lastIndexOf("}") + 1);
  return JSON.parse(json);
}
function writeCatalog(entries) {
  const sorted = Object.fromEntries(Object.entries(entries).sort(([a], [b]) => a.localeCompare(b)));
  writeFileSync(CATALOG, `// Generated by scripts/i18n-extract.mjs from the Polish source texts. Edit texts here or re-run the script.\n// prettier-ignore\nexport const plGenerated = ${JSON.stringify(sorted, null, 2)} as const;\n`);
}

const catalog = readCatalog();
const byPrefixText = new Map(Object.entries(catalog).map(([k, v]) => [`${k.split(".")[0]}\u0000${v}`, k]));
const added = {};
function keyFor(prefix, text) {
  const existing = byPrefixText.get(`${prefix}\u0000${text}`);
  if (existing) return existing;
  const base = `${prefix}.${slugOf(text)}`;
  let key = base;
  for (let n = 2; key in catalog; n++) key = `${base}_${n}`;
  catalog[key] = text;
  added[key] = text;
  byPrefixText.set(`${prefix}\u0000${text}`, key);
  return key;
}

// ── transform ─────────────────────────────────────────────────────────────────
const report = { files: 0, changed: 0, texts: 0, skippedModuleLevel: [] };

function insideFunction(node) {
  for (let p = node.parent; p; p = p.parent) {
    if (ts.isFunctionLike(p) && !ts.isConstructorDeclaration(p)) return true;
  }
  return false;
}
function isAlreadyWrapped(node) {
  const p = node.parent;
  return p && ts.isCallExpression(p) && ts.isIdentifier(p.expression) && (p.expression.text === "t" || p.expression.text === "tp");
}
function renderedInJsx(node) {
  let p = node.parent;
  let child = node;
  while (p && (ts.isConditionalExpression(p) || ts.isParenthesizedExpression(p) || (ts.isBinaryExpression(p) && [ts.SyntaxKind.BarBarToken, ts.SyntaxKind.AmpersandAmpersandToken, ts.SyntaxKind.QuestionQuestionToken].includes(p.operatorToken.kind)))) {
    if (ts.isConditionalExpression(p) && p.condition === child) return false;
    if (ts.isBinaryExpression(p) && p.left === child && p.operatorToken.kind === ts.SyntaxKind.AmpersandAmpersandToken) return false;
    child = p;
    p = p.parent;
  }
  if (!p || !ts.isJsxExpression(p)) return false;
  if (ts.isJsxAttribute(p.parent)) return USER_ATTRS.has(p.parent.name.getText());
  return true;
}
function contextOk(node) {
  if (renderedInJsx(node)) return true;
  const p = node.parent;
  if (p && ts.isPropertyAssignment(p) && p.initializer === node) {
    const name = ts.isIdentifier(p.name) || ts.isStringLiteral(p.name) ? p.name.text : "";
    return USER_PROPS.has(name);
  }
  if (p && ts.isCallExpression(p) && p.arguments.includes(node)) {
    const callee = p.expression;
    const name = ts.isIdentifier(callee) ? callee.text : ts.isPropertyAccessExpression(callee) ? callee.name.text : "";
    return SETTER.test(name);
  }
  return false;
}

function templateCall(sf, node, prefix) {
  // `a ${x} b ${y.z}` → t("key", { x, z: y.z }) with "a {x} b {z}"
  let text = node.head.text;
  const vars = [];
  const used = new Set();
  node.templateSpans.forEach((span, i) => {
    const expr = span.expression;
    let name = ts.isIdentifier(expr) ? expr.text : ts.isPropertyAccessExpression(expr) ? expr.name.text : `v${i}`;
    if (!/^\w+$/.test(name)) name = `v${i}`;
    let unique = name;
    for (let n = 2; used.has(unique); n++) unique = `${name}${n}`;
    used.add(unique);
    vars.push(`${unique}: ${expr.getText(sf)}`);
    text += `{${unique}}${span.literal.text}`;
  });
  if (text.includes("{{") || !looksHuman(text.replace(/\{\w+\}/g, ""))) return null;
  return `t("${keyFor(prefix, text)}", { ${vars.join(", ")} })`;
}

function transform(file) {
  const source = readFileSync(file, "utf8");
  const sf = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const prefix = prefixOf(file);
  const edits = [];
  const visit = (node) => {
    if (ts.isJsxText(node)) {
      const rendered = jsxRendered(node.text);
      const core = rendered.trim();
      if (core && letters(core) >= 2 && !core.includes("{") && insideFunction(node)) {
        const lead = /^\s/.test(rendered) ? '{" "}' : "";
        const trail = /\s$/.test(rendered) ? '{" "}' : "";
        edits.push({ start: node.getStart(sf), end: node.getEnd(), text: `${lead}{t("${keyFor(prefix, core)}")}${trail}` });
        report.texts++;
      }
    } else if (ts.isJsxAttribute(node) && node.initializer && ts.isStringLiteral(node.initializer) && USER_ATTRS.has(node.name.getText())) {
      const value = node.initializer.text;
      if (looksHuman(value) && !value.includes("{") && insideFunction(node)) {
        edits.push({ start: node.initializer.getStart(sf), end: node.initializer.getEnd(), text: `{t("${keyFor(prefix, value)}")}` });
        report.texts++;
      }
    } else if ((ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) && !ts.isJsxAttribute(node.parent) && !isAlreadyWrapped(node) && !ts.isImportDeclaration(node.parent) && !ts.isExportDeclaration(node.parent)) {
      const value = node.text;
      if (looksHuman(value) && !value.includes("{") && contextOk(node)) {
        if (!insideFunction(node)) report.skippedModuleLevel.push(`${path.relative(ROOT, file)}: ${value.slice(0, 60)}`);
        else { edits.push({ start: node.getStart(sf), end: node.getEnd(), text: `t("${keyFor(prefix, value)}")` }); report.texts++; }
      }
    } else if (ts.isTemplateExpression(node) && !isAlreadyWrapped(node) && contextOk(node)) {
      if (!insideFunction(node)) report.skippedModuleLevel.push(`${path.relative(ROOT, file)}: \`${node.head.text.slice(0, 60)}…\``);
      else {
        const call = templateCall(sf, node, prefix);
        if (call) { edits.push({ start: node.getStart(sf), end: node.getEnd(), text: call }); report.texts++; return; }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
  report.files++;
  if (!edits.length) return;
  report.changed++;
  let out = source;
  for (const edit of edits.sort((a, b) => b.start - a.start)) out = out.slice(0, edit.start) + edit.text + out.slice(edit.end);
  if (!/import \{[^}]*\bt\b[^}]*\} from "@\/i18n"/.test(out)) {
    const eol = source.includes("\r\n") ? "\r\n" : "\n";
    const lines = out.split(eol);
    let at = 0;
    while (at < lines.length && (lines[at].startsWith("//") || lines[at].startsWith("\"use ") || lines[at].trim() === "")) at++;
    lines.splice(at, 0, 'import { t } from "@/i18n";');
    out = lines.join(eol);
  }
  if (!dry) writeFileSync(file, out);
}

for (const file of files) transform(path.resolve(file));
if (!dry) writeCatalog(catalog);
const newPath = path.join(ROOT, "scripts/.i18n-new.json");
if (!dry) writeFileSync(newPath, JSON.stringify(added, null, 2));
console.log(JSON.stringify({ ...report, added: Object.keys(added).length, skippedModuleLevel: report.skippedModuleLevel.length }, null, 0));
if (process.env.I18N_SHOW_SKIPPED) console.log(report.skippedModuleLevel.join("\n"));
