#!/usr/bin/env node
// #323-E · collects the API's refusal messages (code + Polish text) from artifacts/api-server/src so the frontend can
// show them in English. Writes src/i18n/catalog/errors.pl.generated.ts: { "errors.<CODE>[.n]": "Polish text" }.
//
//   node scripts/i18n-api-errors.mjs [--dry | --check]
//
// Only object literals that carry a string `code` and a static string `error`/`message` count; messages built at run
// time (template literals) are reported and fall back to the frontend's own localized text.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const ts = require("typescript");

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1")), "..");
const API = path.resolve(ROOT, "../api-server/src");
const OUT = path.join(ROOT, "src/i18n/catalog/errors.pl.generated.ts");
const dry = process.argv.includes("--dry");

const files = [];
(function walk(dir) {
  for (const entry of readdirSync(dir)) {
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) walk(full);
    else if (/\.ts$/.test(entry) && !/\.test\.ts$/.test(entry)) files.push(full);
  }
})(API);

import { polishDetector } from "./i18n-polish.mjs";
const isPolish = polishDetector(ROOT);
const byCode = new Map(); // code → Set(messages)
let dynamic = 0;
const textOf = (node) => (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node) ? node.text : null);
/** Every text an `error:` initializer can produce: literals and templates ("Pole „{v0}” …"), also inside ?: branches. */
function textsOf(node) {
  const out = [];
  const visit = (n) => {
    if (ts.isConditionalExpression(n)) { visit(n.whenTrue); visit(n.whenFalse); return; }
    if (ts.isParenthesizedExpression(n)) { visit(n.expression); return; }
    if (ts.isBinaryExpression(n) && n.operatorToken.kind === ts.SyntaxKind.PlusToken) {
      const left = []; const right = [];
      const collect = (m, into) => { const t = textOf(m); if (t != null) into.push(t); else if (ts.isTemplateExpression(m)) into.push(templateText(m)); else into.push(null); };
      collect(n.left, left); collect(n.right, right);
      if (left[0] != null && right[0] != null) out.push(left[0] + right[0]);
      return;
    }
    const t = textOf(n);
    if (t != null) out.push(t);
    else if (ts.isTemplateExpression(n)) out.push(templateText(n));
  };
  visit(node);
  return out.filter(Boolean);
}
function templateText(node) {
  let text = node.head.text;
  node.templateSpans.forEach((span, i) => { text += `{v${i}}${span.literal.text}`; });
  return text;
}
for (const file of files) {
  const sf = ts.createSourceFile(file, readFileSync(file, "utf8"), ts.ScriptTarget.Latest, true);
  const visit = (node) => {
    if (ts.isObjectLiteralExpression(node)) {
      let code = null; let message = null; let hasDynamic = false;
      for (const prop of node.properties) {
        if (!ts.isPropertyAssignment(prop) || !prop.name || !ts.isIdentifier(prop.name)) continue;
        const name = prop.name.text;
        if (name === "code") code = textOf(prop.initializer);
        if (name === "error" || name === "message") {
          const texts = textsOf(prop.initializer);
          if (texts.length) message = texts; else hasDynamic = true;
        }
      }
      if (code && /^[A-Z][A-Z0-9_]+$/.test(code)) {
        if (!byCode.has(code)) byCode.set(code, new Set());
        for (const text of message ?? []) if (isPolish(text) && text.replace(/\{v\d+\}/g, "").trim().length > 3) byCode.get(code).add(text);
        if (hasDynamic) dynamic++;
      }
      // message maps: { STAGE_NOT_FOUND: "Etap nie istnieje.", … }
      for (const prop of node.properties) {
        if (!ts.isPropertyAssignment(prop) || !prop.name) continue;
        const key = ts.isIdentifier(prop.name) || ts.isStringLiteral(prop.name) ? prop.name.text : "";
        if (!/^[A-Z][A-Z0-9]+(_[A-Z0-9]+)+$/.test(key)) continue;
        for (const text of textsOf(prop.initializer)) {
          if (!isPolish(text) || text.replace(/\{v\d+\}/g, "").trim().length <= 3) continue;
          if (!byCode.has(key)) byCode.set(key, new Set());
          byCode.get(key).add(text);
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
}
const entries = {};
for (const [code, messages] of [...byCode].sort(([a], [b]) => a.localeCompare(b))) {
  const list = [...messages].sort();
  if (list.length === 1) entries[`errors.${code}`] = list[0];
  else list.forEach((message, i) => { entries[`errors.${code}.${i + 1}`] = message; });
}
const body = `// Generated by scripts/i18n-api-errors.mjs from the API's refusal messages. Do not edit by hand.\n// prettier-ignore\nexport const errorsPl = ${JSON.stringify(entries, null, 2)} as const;\n`;
// ── server texts that are not refusals: the preset catalog, plan templates and AI-import notes ─────────────────
// Every Polish literal or template in these files (format names, descriptions, requirements, recommendation reasons,
// default stage names). The frontend shows them — and names new stages — in the viewer's language.
const TEXT_FILES = {
  presets: "domain/tournament/tournament-presets.ts",
  planTemplates: "domain/tournament/tournament-plan-templates.ts",
  aiConfig: "domain/tournament/ai-tournament-config.ts",
  // operations overview and previews (readiness, blockers, next operation)
  operations: "application/operations/tournament-operations.ts",
  progression: "application/operations/tournament-progression-preflight.ts",
  routingPreflight: "application/operations/tournament-qualification-routing-preflight.ts",
  // action-log descriptions the server stores ("Turniej wystartował: 4 graczy …"), shown in the history panels
  routesTournaments: "routes/tournaments.ts",
  routesLeague: "routes/league.ts",
  roster: "application/players/tournament-roster.ts",
  stageLifecycle: "application/stages/stage-lifecycle.ts",
  seedingCeremony: "application/stages/seeding-ceremony.ts",
  twoLegTies: "application/matches/two-leg-ties.ts",
  pointAdjustments: "application/stages/point-adjustments-service.ts",
  // shared libraries the frontend imports directly
  matchRules: "../../../lib/match-rules/src/rules.ts",
  matchSets: "../../../lib/match-rules/src/sets.ts",
  matchTwoLegs: "../../../lib/match-rules/src/two-legs.ts",
  catalogReadiness: "../../../lib/game-catalog/src/steam-catalog-readiness.ts",
};
const fold = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/ł/g, "l").replace(/Ł/g, "L");
const slugOf = (text) => fold(text).toLowerCase().match(/[a-z0-9]+/g)?.slice(0, 5).join("_").slice(0, 40) || "text";
const knownErrors = new Set(Object.values(entries));
const texts = {};
for (const [prefix, rel] of Object.entries(TEXT_FILES)) {
  const sf = ts.createSourceFile(rel, readFileSync(path.join(API, rel), "utf8"), ts.ScriptTarget.Latest, true);
  const seen = new Set();
  const add = (text) => {
    const literal = text.replace(/\{v\d+\}/g, "");
    if (/^\s*[/?#]|[?&]\w+=/.test(text)) return; // URLs and query strings are not text
    if (!isPolish(text) || literal.replace(/[^A-Za-zĄĆĘŁŃÓŚŹŻąćęłńóśźż]/g, "").length < 3 || knownErrors.has(text) || seen.has(text)) return;
    seen.add(text);
    let key = `server.${prefix}.${slugOf(text)}`;
    for (let n = 2; key in texts; n++) key = `server.${prefix}.${slugOf(text)}_${n}`;
    texts[key] = text;
  };
  const visit = (node) => {
    if (ts.isImportDeclaration(node)) return;
    const t = textOf(node);
    if (t != null) add(t);
    else if (ts.isTemplateExpression(node)) add(templateText(node));
    ts.forEachChild(node, visit);
  };
  visit(sf);
}
const textsBody = `// Generated by scripts/i18n-api-errors.mjs from the API's preset catalog, plan templates and AI-import notes.\n// prettier-ignore\nexport const serverPl = ${JSON.stringify(Object.fromEntries(Object.entries(texts).sort(([a], [b]) => a.localeCompare(b))), null, 2)} as const;\n`;
const TEXTS_OUT = path.join(ROOT, "src/i18n/catalog/server.pl.generated.ts");

if (process.argv.includes("--check")) {
  const read = (file) => { try { return readFileSync(file, "utf8").replace(/\r\n/g, "\n"); } catch { return ""; } };
  if (read(OUT) !== body || read(TEXTS_OUT) !== textsBody) { console.error("errors/server catalogs are out of date — run node scripts/i18n-api-errors.mjs"); process.exit(1); }
} else if (!dry) { writeFileSync(OUT, body); writeFileSync(TEXTS_OUT, textsBody); }
console.log(JSON.stringify({ files: files.length, codes: byCode.size, messages: Object.keys(entries).length, codesWithoutStaticText: [...byCode].filter(([, m]) => !m.size).length, dynamicMessages: dynamic, serverTexts: Object.keys(texts).length }));
